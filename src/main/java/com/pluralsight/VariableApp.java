package com.pluralsight;

public class VariableApp {

    public static void main(String[] args) {

        // STEP 1

        // 1. Declare a variable and store your favorite color
        String color = "red";

        //2. Declare a variable to store the year you started this class
        int i = 2026;

        //3. Declare a variable to store your middle initial
        char name = 'A';

        //4. Declare a variable to store whether you have pets
        boolean pet = false;

        //5. Declare a variable with a nice message or saying
        String greeting = "Wagwan";

        System.out.println(color);
        System.out.println(i);
        System.out.println(name);
        System.out.println(pet);
        System.out.println(greeting);


        // STEP 2

        // 1. Number of days in a week
        int week = 7;

        //2. Price of coffee
        double coffee = 4.99;

        //3. Your favorite letter
        char letter = 'S';

        //4. Whether it's raining
        boolean raining = true;

        System.out.println("There are " + week + " days in a week.");
        System.out.println("You will pay " + coffee + " for your drink.");
        System.out.println("My favorite letter is '" + letter + "'.");
        System.out.println("The answer to 'Will it rain today? is: " + raining + ".");









    }
}
